import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

// Preserve source artwork and full composition. 192px covers the 76px UI/HUD
// illustrations at common high-density display sizes without shipping source PNGs.
const root = fileURLToPath(new URL('../', import.meta.url));
const outputRoot = 'src/assets/abilities-runtime';
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) {
  throw new Error('Usage: node scripts/optimize-abilities.mjs [--check]');
}
const names = [
  'assassin', 'cyborg', 'destroyer', 'fanatic', 'goliath', 'half-mutant',
  'hunter', 'mercenary', 'nuclear', 'plasma-nuclear', 'silver-hunter', 'telepath', 'witcher',
];
const settings = {
  resize: { width: 192, height: 192, fit: 'inside', withoutEnlargement: true, kernel: 'lanczos3' },
  webp: { quality: 85, alphaQuality: 100, effort: 6 },
};
const sha256 = buffer => createHash('sha256').update(buffer).digest('hex');
async function saveOrCheck(relativePath, data) {
  const target = path.join(root, relativePath);
  if (check) {
    if (!(await readFile(target)).equals(data)) throw new Error(`${relativePath} is out of date. Run node scripts/optimize-abilities.mjs.`);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, data);
  }
}
const files = [], layers = [], cells = {};
const columns = 4, rows = 4, tileWidth = 192, tileHeight = 192;
for (const [index, name] of names.entries()) {
  const sourcePath = `src/assets/abilities/v1/${name}.png`;
  const original = await readFile(path.join(root, sourcePath));
  const metadata = await sharp(original).metadata();
  const { data, info } = await sharp(original).resize(settings.resize).webp(settings.webp).toBuffer({ resolveWithObject: true });
  const outputPath = `${outputRoot}/${name}.webp`;
  if (info.width > settings.resize.width || info.height > settings.resize.height) throw new Error(`${outputPath}: display budget exceeded.`);
  await saveOrCheck(outputPath, data);
  // Compose resized source pixels directly, avoiding a second lossy WebP encode.
  const { data: pixels, info: pixelInfo } = await sharp(original).resize(settings.resize).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  if (pixelInfo.width !== tileWidth || pixelInfo.height !== tileHeight) throw new Error(`${sourcePath}: expected square ability icon.`);
  const column = index % columns, row = Math.floor(index / columns);
  const x = column * tileWidth, y = row * tileHeight;
  layers.push({ input: pixels, raw: { width: tileWidth, height: tileHeight, channels: 4 }, left: x, top: y });
  cells[name] = { column, row, x, y, width: tileWidth, height: tileHeight };
  if (!(await readFile(path.join(root, sourcePath))).equals(original)) throw new Error(`${sourcePath} changed during generation.`);
  files.push({
    source: { path: sourcePath, width: metadata.width, height: metadata.height, bytes: original.length, sha256: sha256(original) },
    output: { path: outputPath, width: info.width, height: info.height, bytes: data.length, sha256: sha256(data) },
  });
}
const atlas = await sharp({ create: { width: columns * tileWidth, height: rows * tileHeight, channels: 4, background: '#00000000' } })
  .composite(layers).webp(settings.webp).toBuffer();
await saveOrCheck(`${outputRoot}/abilities.webp`, atlas);
const layout = { columns, rows, tileWidth, tileHeight, cells };
await saveOrCheck(`${outputRoot}/ability-layout.ts`, Buffer.from(`// Generated by scripts/optimize-abilities.mjs; do not edit.\nexport const ABILITY_LAYOUT = ${JSON.stringify(layout, null, 2)} as const;\n`));
await saveOrCheck(`${outputRoot}/manifest.json`, Buffer.from(`${JSON.stringify({
  schemaVersion: 1, generator: 'scripts/optimize-abilities.mjs',
  sharpVersion: sharp.versions.sharp, libvipsVersion: sharp.versions.vips, settings,
  verification: { originalsPreserved: true, decodedPixelsEqualSource: false }, files,
  atlas: { ...layout, path: `${outputRoot}/abilities.webp`, width: columns * tileWidth, height: rows * tileHeight, bytes: atlas.length, sha256: sha256(atlas), encodedDirectlyFromResizedSource: true },
}, null, 2)}\n`));
const before = files.reduce((sum, file) => sum + file.source.bytes, 0);
const after = files.reduce((sum, file) => sum + file.output.bytes, 0);
console.log(`${check ? 'Verified' : 'Generated'} ${files.length} runtime ability icons; originals preserved.`);
console.log(`${before} -> ${after} bytes (${(100 * (1 - after / before)).toFixed(1)}% smaller).`);
console.log(`Shared ability atlas ${columns * tileWidth}x${rows * tileHeight}: ${atlas.length} bytes.`);
