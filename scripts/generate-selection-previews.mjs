import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// Tiny first-paint artwork is bundled in JavaScript; full-quality assets replace
// it independently. Encode originals directly and preserve every source file.
const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw Error('Usage: node scripts/generate-selection-previews.mjs [--check]');
const roster = JSON.parse(await readFile(path.join(root, 'src/assets/portraits-runtime/roster-layout.json'), 'utf8'));
const abilities = JSON.parse(await readFile(path.join(root, 'src/assets/abilities-runtime/manifest.json'), 'utf8'));
const settings = {
    portrait: { width: 96, height: 144, quality: 65 },
    roster: { width: 64, height: 96, quality: 65 },
    ability: { width: 48, height: 48, quality: 70 },
    kernel: 'lanczos3', alphaQuality: 100, effort: 6,
};
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const uri = bytes => `data:image/webp;base64,${bytes.toString('base64')}`;
const sources = [], portraits = {}, portraitOutputs = [], rosterLayers = [], abilityLayers = [];

async function sourceFile(source) {
    const relative = source.path;
    const bytes = await readFile(path.join(root, relative));
    if (hash(bytes) !== source.sha256) throw Error(`${relative}: original changed; regenerate its source manifest first`);
    sources.push({ path: relative, bytes: bytes.length, sha256: source.sha256 });
    return bytes;
}
async function encoded(source, size) {
    return sharp(source).resize(size.width, size.height, { fit: 'fill', kernel: settings.kernel })
        .webp({ quality: size.quality, alphaQuality: settings.alphaQuality, effort: settings.effort }).toBuffer();
}
async function layer(source, size, cell) {
    const { data, info } = await sharp(source).resize(size.width, size.height, { fit: 'fill', kernel: settings.kernel })
        .ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    return { input: data, raw: { width: info.width, height: info.height, channels: 4 },
        left: cell.column * size.width, top: cell.row * size.height };
}
async function atlas(layers, size, columns, rows) {
    return sharp({ create: { width: size.width * columns, height: size.height * rows,
        channels: 4, background: '#00000000' } }).composite(layers)
        .webp({ quality: size.quality, alphaQuality: settings.alphaQuality, effort: settings.effort }).toBuffer();
}
async function save(relative, bytes) {
    const absolute = path.join(root, relative);
    if (check) {
        if (!(await readFile(absolute)).equals(bytes)) throw Error(`${relative} is out of date; run node scripts/generate-selection-previews.mjs`);
    } else { await mkdir(path.dirname(absolute), { recursive: true }); await writeFile(absolute, bytes); }
}

if (roster.manifest.sources.length !== 15 || Object.keys(roster.cells).length !== 15
    || abilities.files.length !== 13 || Object.keys(abilities.atlas.cells).length !== 13) {
    throw Error('Selection inventory changed; review preview exporter');
}
for (const source of roster.manifest.sources) {
    const bytes = await sourceFile(source);
    const id = source.id;
    const cell = roster.cells[id];
    if (!cell) throw Error(`Missing roster cell: ${id}`);
    const portrait = await encoded(bytes, settings.portrait);
    portraits[id] = uri(portrait);
    portraitOutputs.push({ id, bytes: portrait.length, sha256: hash(portrait) });
    rosterLayers.push(await layer(bytes, settings.roster, cell));
}
for (const entry of abilities.files) {
    const source = entry.source;
    const id = path.basename(source.path, '.png');
    const cell = abilities.atlas.cells[id];
    if (!cell) throw Error(`Missing ability cell: ${id}`);
    abilityLayers.push(await layer(await sourceFile(source), settings.ability, cell));
}
const rosterBytes = await atlas(rosterLayers, settings.roster, roster.columns, roster.rows);
const abilityBytes = await atlas(abilityLayers, settings.ability, abilities.atlas.columns, abilities.atlas.rows);
const totalBytes = portraitOutputs.reduce((sum, entry) => sum + entry.bytes, 0) + rosterBytes.length + abilityBytes.length;
if (totalBytes > 80_000) throw Error(`Preview budget exceeded: ${totalBytes} bytes > 80000`);
for (const source of sources) {
    if (hash(await readFile(path.join(root, source.path))) !== source.sha256) throw Error(`${source.path}: concurrent source change`);
}
const module = Buffer.from(`// Generated by scripts/generate-selection-previews.mjs. First-paint previews only; full-quality assets are unchanged.\nimport type { CharacterId } from '@/gameplay/ids';\n\nexport const PORTRAIT_PREVIEWS: Readonly<Record<CharacterId, string>> = ${JSON.stringify(portraits, null, 2)};\n\nexport const ROSTER_PREVIEW = ${JSON.stringify(uri(rosterBytes))};\n\nexport const ABILITY_PREVIEW = ${JSON.stringify(uri(abilityBytes))};\n`);
await save('src/assets/selection-preview-data.ts', module);
await save('src/assets/selection-preview-manifest.json', Buffer.from(`${JSON.stringify({
    generator: 'scripts/generate-selection-previews.mjs', schemaVersion: 1,
    sharpVersion: sharp.versions.sharp, libvipsVersion: sharp.versions.vips, settings,
    originalsPreserved: true, sources,
    portraits: portraitOutputs,
    roster: { columns: roster.columns, rows: roster.rows, bytes: rosterBytes.length, sha256: hash(rosterBytes) },
    abilities: { columns: abilities.atlas.columns, rows: abilities.atlas.rows, bytes: abilityBytes.length, sha256: hash(abilityBytes) },
    totalBinaryBytes: totalBytes, moduleBytes: module.length, moduleSha256: hash(module),
}, null, 2)}\n`));
console.log(`${check ? 'Verified' : 'Generated'} 15 embedded portraits + roster + abilities: ${totalBytes} image bytes, ${module.length} TypeScript bytes; originals preserved.`);
