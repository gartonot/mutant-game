import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

// Encode original resized pixels once; never recompress the lossy thumbnails.
const root = fileURLToPath(new URL('../', import.meta.url));
const outputRoot = 'src/assets/portraits-runtime';
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/optimize-roster.mjs [--check]');
const names = [
  'assassin', 'destroyer', 'mercenary', 'hunter', 'cyborg', 'telepath',
  'fanatic', 'witcher', 'plasma-nuclear', 'nuclear', 'silver-hunter',
  'goliath', 'half-mutant', 'unknown-white-outfit-v1', 'unknown-crossbow-v3',
];
const columns = 5, rows = 3, tileWidth = 192, tileHeight = 288;
const settings = {
  resize: { width: tileWidth, height: tileHeight, fit: 'inside', withoutEnlargement: true, kernel: 'lanczos3' },
  webp: { quality: 85, alphaQuality: 100, effort: 6 },
};
const sha256 = data => createHash('sha256').update(data).digest('hex');
async function saveOrCheck(relativePath, data) {
  const target = path.join(root, relativePath);
  if (check) {
    if (!(await readFile(target)).equals(data)) throw new Error(`${relativePath} is out of date. Run node scripts/optimize-roster.mjs.`);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, data);
  }
}
const layers = [], files = [], cells = {};
for (const [index, name] of names.entries()) {
  const id = name.replace(/-v[13]$/, '');
  const sourcePath = `src/assets/characters/${name}.png`;
  const source = await readFile(path.join(root, sourcePath));
  const metadata = await sharp(source).metadata();
  const { data, info } = await sharp(source).resize(settings.resize).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  if (info.width !== tileWidth || info.height !== tileHeight) throw new Error(`${sourcePath}: expected portrait aspect ratio 2:3.`);
  const column = index % columns, row = Math.floor(index / columns);
  layers.push({ input: data, raw: { width: tileWidth, height: tileHeight, channels: 4 }, left: column * tileWidth, top: row * tileHeight });
  cells[id] = { column, row };
  files.push({ id, path: sourcePath, width: metadata.width, height: metadata.height, bytes: source.length, sha256: sha256(source), resizedRgbaSha256: sha256(data) });
  if (!(await readFile(path.join(root, sourcePath))).equals(source)) throw new Error(`${sourcePath} changed during generation.`);
}
const atlas = await sharp({ create: { width: columns * tileWidth, height: rows * tileHeight, channels: 4, background: '#00000000' } })
  .composite(layers).webp(settings.webp).toBuffer();
await saveOrCheck(`${outputRoot}/roster.webp`, atlas);
await saveOrCheck(`${outputRoot}/roster-layout.json`, Buffer.from(`${JSON.stringify({
  schemaVersion: 1, generator: 'scripts/optimize-roster.mjs', columns, rows, tileWidth, tileHeight,
  width: columns * tileWidth, height: rows * tileHeight, cells,
  manifest: { sharpVersion: sharp.versions.sharp, libvipsVersion: sharp.versions.vips, settings,
    output: { path: `${outputRoot}/roster.webp`, bytes: atlas.length, sha256: sha256(atlas) },
    verification: { originalsPreserved: true, encodedDirectlyFromResizedSource: true }, sources: files },
}, null, 2)}\n`));
await saveOrCheck(`${outputRoot}/roster-layout.ts`, Buffer.from(`// Generated by scripts/optimize-roster.mjs; do not edit.\nexport const ROSTER_LAYOUT = ${JSON.stringify({ columns, rows, cells }, null, 2)} as const;\n`));
console.log(`${check ? 'Verified' : 'Generated'} ${columns}x${rows} roster atlas (${columns * tileWidth}x${rows * tileHeight}), ${atlas.length} bytes; originals preserved.`);
