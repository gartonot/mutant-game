import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw Error('Usage: node scripts/optimize-character-textures.mjs [--check]');
const inventory = JSON.parse(await readFile(path.join(root, 'src/assets/combat-runtime/manifest.json'), 'utf8'));
const outputRoot = 'src/assets/combat-scaled';
const settings = { scale: .5, kernel: 'lanczos3', png: { compressionLevel: 9, adaptiveFiltering: true, palette: false } };
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const dimensions = {}, files = [];
async function save(relative, bytes) {
    const absolute = path.join(root, relative);
    if (check) {
        if (!(await readFile(absolute)).equals(bytes)) throw Error(`${relative} is out of date`);
    } else { await mkdir(path.dirname(absolute), { recursive: true }); await writeFile(absolute, bytes); }
}
for (const entry of inventory.files.filter(file => file.category === 'characters')) {
    const source = await readFile(path.join(root, entry.source.path));
    if (hash(source) !== entry.source.sha256) throw Error(`${entry.source.path}: original changed; review source inventory`);
    const { width: sourceWidth, height: sourceHeight } = await sharp(source).metadata();
    const width = Math.ceil(sourceWidth * settings.scale), height = Math.ceil(sourceHeight * settings.scale);
    const bytes = await sharp(source).resize(width, height, { fit: 'fill', kernel: settings.kernel }).png(settings.png).toBuffer();
    const relative = `${outputRoot}/characters/${entry.id}.png`;
    await save(relative, bytes);
    dimensions[entry.id] = { sourceWidth, sourceHeight, width, height, scaleX: width / sourceWidth, scaleY: height / sourceHeight };
    files.push({ id: entry.id, source: entry.source, output: { path: relative, bytes: bytes.length, sha256: hash(bytes), ...dimensions[entry.id] } });
    if (!(await readFile(path.join(root, entry.source.path))).equals(source)) throw Error('Concurrent original change');
}
await save(`${outputRoot}/dimensions.ts`, Buffer.from(`// Generated by scripts/optimize-character-textures.mjs. Authoring coordinates remain unchanged.\nexport const CHARACTER_TEXTURES = ${JSON.stringify(dimensions, null, 2)} as const;\n`));
await save(`${outputRoot}/manifest.json`, Buffer.from(`${JSON.stringify({ generator: 'scripts/optimize-character-textures.mjs', settings, sharpVersion: sharp.versions.sharp, libvipsVersion: sharp.versions.vips, originalsPreserved: true, files }, null, 2)}\n`));
console.log(`${check ? 'Verified' : 'Generated'} ${files.length} character textures: ${files.reduce((n,f)=>n+f.source.bytes,0)} -> ${files.reduce((n,f)=>n+f.output.bytes,0)} bytes; half resolution, authoring coordinates preserved.`);
