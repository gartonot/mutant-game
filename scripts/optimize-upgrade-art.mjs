import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputRoot = 'src/assets/upgrades-runtime';
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw Error('Usage: node scripts/optimize-upgrade-art.mjs [--check]');
const inventory = JSON.parse(await readFile(path.join(root, 'src/assets/icons-runtime/manifest.json'), 'utf8'));
const names = ['health-v2', 'attack-speed-v2', 'damage-v2', 'move-speed-v2', 'armor-v2', 'arsenal-pistol-v2', 'arsenal-automatic-v2', 'arsenal-shotgun-v2', 'arsenal-heavy-v2', 'arsenal-energy-v2'];
const columns = 5, rows = 2, tileSize = 192;
const settings = { tileSize, previewSize: 64, kernel: 'lanczos3', webp: { quality: 90, alphaQuality: 100, effort: 6 }, preview: { quality: 65, alphaQuality: 100, effort: 6 } };
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const layers = [], previews = [], files = [], cells = {};
async function save(relative, bytes) {
    const absolute = path.join(root, relative);
    if (check) { if (!(await readFile(absolute)).equals(bytes)) throw Error(`${relative} is out of date`); }
    else { await mkdir(path.dirname(absolute), { recursive: true }); await writeFile(absolute, bytes); }
}
for (const [index, id] of names.entries()) {
    const entry = inventory.files.find(file => file.output.path === `src/assets/icons-runtime/upgrades/${id}.png`);
    if (!entry) throw Error(`Missing source: ${id}`);
    const source = await readFile(path.join(root, entry.source.path));
    if (hash(source) !== entry.source.sha256) throw Error(`Original changed: ${entry.source.path}`);
    const column = index % columns, row = Math.floor(index / columns);
    const input = await sharp(source).resize(tileSize, tileSize, { fit: 'cover', kernel: settings.kernel }).png().toBuffer();
    const preview = await sharp(source).resize(64, 64, { fit: 'cover', kernel: settings.kernel }).png().toBuffer();
    layers.push({ input, left: column * tileSize, top: row * tileSize });
    previews.push({ input: preview, left: column * 64, top: row * 64 });
    cells[id] = { column, row, x: column * tileSize, y: row * tileSize, width: tileSize, height: tileSize };
    files.push({ id, source: entry.source, previous: entry.output });
    if (!(await readFile(path.join(root, entry.source.path))).equals(source)) throw Error('Concurrent source change');
}
const make = (size, inputs, options) => sharp({ create: { width: columns * size, height: rows * size, channels: 4, background: '#00000000' } }).composite(inputs).webp(options).toBuffer();
const atlas = await make(tileSize, layers, settings.webp), preview = await make(64, previews, settings.preview);
if (preview.length > 25000) throw Error('Embedded upgrade preview exceeds 25KB budget');
await save(`${outputRoot}/upgrades.webp`, atlas);
await save(`${outputRoot}/layout.ts`, Buffer.from(`// Generated by scripts/optimize-upgrade-art.mjs.\nexport const UPGRADE_LAYOUT = ${JSON.stringify({ columns, rows, tileSize, cells }, null, 2)} as const;\n`));
await save(`${outputRoot}/preview.ts`, Buffer.from(`// Generated by scripts/optimize-upgrade-art.mjs.\nexport const UPGRADE_PREVIEW = 'data:image/webp;base64,${preview.toString('base64')}';\n`));
await save(`${outputRoot}/manifest.json`, Buffer.from(`${JSON.stringify({ generator: 'scripts/optimize-upgrade-art.mjs', settings, sharpVersion: sharp.versions.sharp, libvipsVersion: sharp.versions.vips, originalsPreserved: true, files, output: { bytes: atlas.length, sha256: hash(atlas) }, preview: { bytes: preview.length, sha256: hash(preview) } }, null, 2)}\n`));
console.log(`${check ? 'Verified' : 'Generated'} 10 upgrade icons: ${files.reduce((n, f) => n + f.previous.bytes, 0)} -> ${atlas.length} bytes; preview ${preview.length} bytes; originals preserved.`);
